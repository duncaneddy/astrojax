"""Cross-validation tests: astrojax access vs Brahe v1.1.2.

Uses a shared ECEF trajectory (from Brahe's SGP4) with Hermite interpolation
and float64 to isolate the access algorithm from propagation/frame errors.

Fixture data: tests/fixtures/access_brahe_trajectory.npz
Generated by: tests/fixtures/generate_access_brahe_fixtures.py
"""

from pathlib import Path

import jax.numpy as jnp
import numpy as np
import pytest

from astrojax.access import find_access_windows, ground_location
from astrojax.access.constraints import (
    constraint_all,
    elevation_constraint,
    off_nadir_constraint,
)
from astrojax.config import set_dtype
from astrojax.utils.interpolation import make_hermite_position_fn

# ---------------------------------------------------------------------------
# Tolerances
# ---------------------------------------------------------------------------

_TIME_TOL = 0.05  # seconds — both algorithms refine to ~0.01s
_DURATION_TOL = 0.1  # seconds

# ---------------------------------------------------------------------------
# Fixture path
# ---------------------------------------------------------------------------

_FIXTURE_PATH = Path(__file__).parent.parent / "fixtures" / "access_brahe_trajectory.npz"


@pytest.fixture(scope="module")
def fixture_data():
    """Load the Brahe fixture and build Hermite interpolated position function.

    Sets dtype to float64 for the duration of this module.
    """
    set_dtype(jnp.float64)

    data = np.load(_FIXTURE_PATH)

    times = jnp.array(data["times_s"], dtype=jnp.float64)
    positions = jnp.array(data["positions_ecef"], dtype=jnp.float64)
    velocities = jnp.array(data["velocities_ecef"], dtype=jnp.float64)

    pos_fn = make_hermite_position_fn(times, positions, velocities)

    loc = ground_location(
        lon=float(data["station_lon_deg"]),
        lat=float(data["station_lat_deg"]),
        alt=0.0,
        use_degrees=True,
    )

    return {
        "pos_fn": pos_fn,
        "loc": loc,
        "t_start": 0.0,
        "t_end": float(times[-1]),
        "data": data,
    }


