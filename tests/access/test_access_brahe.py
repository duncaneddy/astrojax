class TestConstraintNarrowsWindows:
    """Verify constraint relationships hold."""

    def test_higher_elevation_narrows(self, fixture_data):
        """5-degree elevation windows should be shorter than 0-degree windows."""
        data = fixture_data["data"]
        dur_el0 = data["el0_duration"]
        dur_el5 = data["el5_duration"]

        # Same window count, but each 5-deg window is shorter
        assert len(dur_el0) == len(dur_el5)
        for i in range(len(dur_el0)):
            assert dur_el5[i] < dur_el0[i] + 0.1, (
                f"Window {i}: el5 duration ({dur_el5[i]:.1f}s) should be "
                f"shorter than el0 ({dur_el0[i]:.1f}s)"
            )

    def test_composed_narrows(self, fixture_data):
        """AND-composed windows are subsets of individual constraint windows.

        Each combined window (el >= 5 AND off-nadir <= 60) must be contained
        within some el >= 5 window and some off-nadir <= 60 window.
        """
        data = fixture_data["data"]
        combined_rise = data["combined_t_rise"]
        combined_set = data["combined_t_set"]
        el5_rise = data["el5_t_rise"]
        el5_set = data["el5_t_set"]
        on60_rise = data["on60_t_rise"]
        on60_set = data["on60_t_set"]

        for i in range(len(combined_rise)):
            cr, cs = combined_rise[i], combined_set[i]

            # Must be contained in some el >= 5 window
            contained_in_el5 = any(
                er <= cr + _TIME_TOL and es >= cs - _TIME_TOL
                for er, es in zip(el5_rise, el5_set, strict=True)
            )
            assert contained_in_el5, (
                f"Combined window {i} [{cr:.1f}, {cs:.1f}] not contained in any el >= 5 window"
            )

            # Must be contained in some off-nadir <= 60 window
            contained_in_on60 = any(
                or_ <= cr + _TIME_TOL and os_ >= cs - _TIME_TOL
                for or_, os_ in zip(on60_rise, on60_set, strict=True)
            )
            assert contained_in_on60, (
                f"Combined window {i} [{cr:.1f}, {cs:.1f}] not contained "
                f"in any off-nadir <= 60 window"
            )
